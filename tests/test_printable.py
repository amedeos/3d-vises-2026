"""Every part is a valid, watertight single body that fits the MK4; the 3MF plates are
right (placement, names, colour changes); the optional slicer step builds projects."""

import re
import zipfile
from itertools import combinations

import pytest

from common.export import BED, COLOURS, M600_ENTRY, check, mesh_problems, write_3mf
from common.slicer import (CONFIG_ENTRY, MK4_BED, config_from_gcode, make_project,
                           start_colours, with_start_colour)
from conftest import all_parts, all_plates, parts, plates

PARTS = all_parts()
PLATES = all_plates()


@pytest.mark.parametrize("model,name", PARTS)
def test_part_is_printable(model, name):
    """Valid solid, one body (print-in-place parts are one piece), on the bed, fits."""
    assert check(parts(model)[name]) == []


@pytest.mark.parametrize("model,name", PARTS)
def test_stl_mesh_is_watertight(model, name):
    assert mesh_problems(parts(model)[name]) == []


@pytest.mark.parametrize("model,plate", PLATES)
def test_plate_fits_the_bed_without_overlaps(model, plate):
    objects, _ = plates(model)[plate]
    boxes = [part.bounding_box() for _, part, _ in objects]
    for bb in boxes:
        assert bb.min.X >= 0 and bb.min.Y >= 0 and abs(bb.min.Z) < 1e-3
        assert bb.max.X <= BED[0] and bb.max.Y <= BED[1] and bb.max.Z <= BED[2]
    for a, b in combinations(boxes, 2):
        assert a.max.X < b.min.X or b.max.X < a.min.X or a.max.Y < b.min.Y or b.max.Y < a.min.Y


@pytest.mark.parametrize("model,plate", PLATES)
def test_plate_is_centred_on_the_bed(model, plate):
    # PrusaSlicer arranges around the middle of the bed; the plates start there too
    objects, _ = plates(model)[plate]
    boxes = [part.bounding_box() for _, part, _ in objects]
    x0, x1 = min(b.min.X for b in boxes), max(b.max.X for b in boxes)
    y0, y1 = min(b.min.Y for b in boxes), max(b.max.Y for b in boxes)
    assert (x0 + x1) / 2 == pytest.approx(BED[0] / 2, abs=0.5)
    assert (y0 + y1) / 2 == pytest.approx(BED[1] / 2, abs=0.5)


@pytest.mark.parametrize("model,plate", PLATES)
def test_plate_starts_in_one_colour(model, plate):
    # one extruder: every object on a plate starts with the same filament, and the
    # project's filament colour is that one
    objects, _ = plates(model)[plate]
    assert len({colour for _, _, colour in objects}) == 1


@pytest.mark.parametrize("model,plate", PLATES)
def test_3mf_content(tmp_path, model, plate):
    objects, changes = plates(model)[plate]
    path = tmp_path / f"{plate}.3mf"
    write_3mf(path, objects, changes)
    z = zipfile.ZipFile(path)
    xml_model = z.read("3D/3dmodel.model").decode()
    assert 'unit="millimeter"' in xml_model
    assert re.findall(r'<object [^>]*name="([^"]*)"', xml_model) == [n for n, _, _ in objects]
    if not changes:
        assert M600_ENTRY not in z.namelist()
        return
    xml = z.read(M600_ENTRY).decode()
    for print_z, _ in changes:
        assert f'print_z="{print_z:.2f}"' in xml
    assert xml.count('gcode="M600"') == len(changes)
    # the PrusaSlicer 2.9 GUI ignores colour changes without a bed index
    assert xml.count('bed_idx="0"') == len(changes) + 1


def test_too_many_colour_changes_are_refused(tmp_path):
    objects, _ = next(iter(plates("tux_clip").values()))
    with pytest.raises(ValueError):
        write_3mf(tmp_path / "x.3mf", objects, [(1.0, "white"), (2.0, "orange"),
                                                (3.0, "white"), (4.0, "orange")])


def test_project_gets_the_config_from_the_gcode(tmp_path):
    gcode = tmp_path / "x.gcode"
    gcode.write_text("; generated by PrusaSlicer 2.9.6\nG1 X1\n; prusaslicer_config = begin\n"
                     "; binary_gcode = 0\n; filament_colour = #FF8000\n; layer_height = 0.2\n"
                     "; prusaslicer_config = end\n")
    config = config_from_gcode(gcode)
    assert "; binary_gcode = 1" in config and "; layer_height = 0.2" in config
    objects, changes = plates("tux_clip")["tux_clip_S"]
    plate = tmp_path / "plate.3mf"
    write_3mf(plate, objects, changes)
    # Tux starts in black, not in the orange of the Prusament PETG profile
    assert start_colours(plate) == {COLOURS["black"].upper()}
    config = with_start_colour(config, *start_colours(plate))
    assert "; filament_colour = #1C1A1E" in config and "#FF8000" not in config
    project = tmp_path / "projects" / "plate.3mf"
    make_project(plate, config, project)
    assert zipfile.ZipFile(project).read(CONFIG_ENTRY).decode() == config
    with pytest.raises(ValueError):
        with_start_colour("; layer_height = 0.2\n", "#1C1A1E")


@pytest.mark.parametrize("bed", [MK4_BED, "0x0,200x0,200x200,0x200"])
def test_slicer_writes_a_project_only_with_the_mk4_profiles(tmp_path, monkeypatch, bed):
    """Without the MK4 profiles PrusaSlicer slices with its defaults (a 200 x 200 bed): the
    plate is flagged and no project is written. With them, the project starts in the
    plate's colour. PrusaSlicer itself is replaced by a fake that echoes the config."""
    import common.slicer as slicer

    def fake_slice(cmd, plate, gcode, profiles=True, extra=()):
        config = [f"; bed_shape = {bed}", "; filament_colour = #FF8000",
                  "; printer_settings_id = MK4"]
        with zipfile.ZipFile(plate) as z:  # a project: PrusaSlicer loads its own config
            if CONFIG_ENTRY in z.namelist():
                config = z.read(CONFIG_ENTRY).decode().splitlines()[1:]
        gcode.write_text("\n".join(["; generated by PrusaSlicer 2.9.6", "G1 X1",
                                     "; prusaslicer_config = begin", *config,
                                     "; prusaslicer_config = end", ""]))

    monkeypatch.setattr(slicer, "prusaslicer_command", lambda: ["prusa-slicer"])
    monkeypatch.setattr(slicer, "slice_plate", fake_slice)
    objects, changes = plates("tux_clip")["coupon_flexure"]
    write_3mf(tmp_path / "coupon_flexure.3mf", objects, changes)
    project = tmp_path / "projects" / "coupon_flexure.3mf"
    if bed == MK4_BED:
        assert slicer.main(tmp_path, {}, "tux_clip") == 0
        config = zipfile.ZipFile(project).read(CONFIG_ENTRY).decode()
        assert f"; filament_colour = {COLOURS[objects[0][2]].upper()}" in config
    else:
        assert slicer.main(tmp_path, {}, "tux_clip") == 1
        assert not project.exists()
